def tls_server(source: str) -> str:
    start = source.index("http::response<http::string_body> res;")
    response = source[start:source.index("co_await http::async_write", start)]
    return PREFIX + """
// The embedding host must authenticate clients before invoking this handler.
// The test's TLS frontend enforces mutual TLS and rejects missing identities.
#ifndef WEBCPP_BEAST_HOST_MTLS_CONFIRMED
#error "This counterpart requires a host configured to enforce mutual TLS"
#endif
http::response<http::string_body> handle(const http::request<http::string_body>& /*unused*/) {
""" + response + """
    res.prepare_payload();
    return res;
}
}  // namespace
WEBCPP_BEAST_WASI_HTTP_EXPORT(handle)
"""


SOURCES = {
    "http-server-fast": ("http/server/fast/http_server_fast.cpp", fast),
    "http-server-small": ("http/server/small/http_server_small.cpp", small),
    "doc-ssl-server": ("doc/ssl/server.cpp", tls_server),
}


def generate(formatter: str) -> None:
    mapping = []
    for name, (relative, transform) in SOURCES.items():
        source = (UPSTREAM / relative).read_text()
        notice = source[:source.index("#include")]
        text = NOTICE + notice + transform(source)
        path = HERE / (name + ".cpp")
        result = subprocess.run([formatter, f"--assume-filename={path}",
                                 "--style={BasedOnStyle: InheritParentConfig, InsertBraces: true}"],
                                input=text,
                                text=True, capture_output=True, check=True)
        if not path.exists() or path.read_text() != result.stdout:
            path.write_text(result.stdout)
        difference = "".join(difflib.unified_diff(
            source.splitlines(True), result.stdout.splitlines(True),
            fromfile="upstream/" + relative, tofile="host-extra/" + path.name))
        (HERE / (name + ".diff")).write_text(difference)
        mapping.append({"id": name, "upstream": relative, "source": path.name})
    (HERE / "mapping.json").write_text(json.dumps({
        "applications": mapping,
        "adaptations": [
            "The host owns connection acceptance, framing, persistence and TLS.",
            "Fast retains GET-only path/error/file logic; host fields use the default allocator.",
            "Small retains /count and /time; counter lifetime is the host component instance.",
            "The TLS example requires an explicit host mutual-TLS capability assertion."
        ]}, indent=2) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--clang-format", required=True)
    generate(parser.parse_args().clang_format)
