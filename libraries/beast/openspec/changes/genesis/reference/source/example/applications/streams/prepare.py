"""Retain the original local HTTP server's routing and response-body choices."""
from pathlib import Path
import re
import subprocess
import sys

HERE = Path(__file__).resolve().parent
SOURCE = (HERE.parents[1] / 'upstream/http/server/async-local' /
          'http_server_async_local.cpp')
source = SOURCE.read_text()
notice = source[:source.index('//-----')]
match = re.search(r'beast::string_view\s+mime_type\(', source)
assert match is not None
start = match.start()
opening = source.index('{', source.index('\nhandle_request('))
end, depth = opening + 1, 1
while depth:
    depth += (source[end] == '{') - (source[end] == '}')
    end += 1
handler = source[start:end].replace('http::message_generator', 'application_response')
handler = handler.replace('std::make_tuple(http::status::ok, req.version())}',
                          'std::make_tuple(http::status::ok, req.version()),}')
text = '''// Copyright (c) 2026 WebCpp.org
//
// Distributed under the Boost Software License, Version 1.0. (See
// accompanying file LICENSE_1_0.txt or copy at
// https://www.boost.org/LICENSE_1_0.txt)

''' + notice + '''// Generated by streams/prepare.py. Edit the generator.
// The original routing/file handler uses an explicit supplied byte stream.
#include <webcpp/beast/core.hpp>
#include <webcpp/beast/wasi/stream.hpp>
#include <boost/beast/version.hpp>
#include <cstdio>
#include <variant>
namespace beast = webcpp::beast;
namespace http = beast::http;
using application_response = std::variant<http::response<http::string_body>,
    http::response<http::empty_body>, http::response<http::file_body>>;
namespace {
''' + handler + '''
} // namespace
int main() {
    beast::wasi::stdio_stream channel;
    beast::flat_buffer input;
    for (;;) {
        http::request_parser<http::string_body> parser;
        boost::system::error_code error;
        beast::wasi::read(channel, input, parser, error);
        if (error == http::error::end_of_stream) return 0;
        if (error) {
            static_cast<void>(std::fprintf(stderr, "read: %s\\n", error.message().c_str()));
            return 1;
        }
        auto response = handle_request(".", parser.release());
        bool keep_alive = false;
        std::visit([&](auto& message) {
            keep_alive = message.keep_alive();
            beast::wasi::write(channel, message, error);
        }, response);
        if (error) {
            static_cast<void>(std::fprintf(stderr, "write: %s\\n", error.message().c_str()));
            return 2;
        }
        if (!keep_alive) return 0;
    }
}
'''
formatter = sys.argv[1] if len(sys.argv) > 1 else 'clang-format'
result = subprocess.run([formatter, '--assume-filename=http-server-async-local.cpp',
                         '-style={BasedOnStyle: InheritParentConfig, InsertBraces: true}'],
                        input=text, text=True, capture_output=True, check=True)
(HERE / 'http-server-async-local.cpp').write_text(result.stdout)
